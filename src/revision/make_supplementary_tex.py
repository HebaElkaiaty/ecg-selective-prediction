"""Build Supplementary Tables S1-S4 as LaTeX (booktabs) from the generated CSVs.

Conventions
  - A class without a usable operating point shows "---", never 0.0000 or 1.000:
    a threshold of zero flags every record and is not a threshold anyone would
    deploy, so printing it as a number invites it to be read as one.
  - Status distinguishes "uncertifiable" (cannot reject H0 at any lambda) from
    "trivial" (clears the floor, but no lambda > 0 passes the test).
  - Seed 0 throughout unless the table says otherwise.
"""
from __future__ import annotations
import csv, json, sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from src.revision.paths import OUT, CKPT_ROOT, SEEDS

TEX = OUT / "supplementary_tables.tex"
ORD = {"Critical": 0, "Important": 1, "Benign": 2}
DASH = r"---"


def rd(name):
    return list(csv.DictReader(open(OUT / name)))


def esc(s: str) -> str:
    """LaTeX-escape a class name. Underscores are common here (_AVB, ISC_, NST_)."""
    return s.replace("_", r"\_")


def num(v, nd=4, dash_if=None):
    if v in ("", None):
        return DASH
    x = float(v)
    if dash_if is not None and dash_if(x):
        return DASH
    return f"{x:.{nd}f}"


def lam(v, status_ok=True):
    """Thresholds span six orders of magnitude; print small ones in scientific
    notation so a positive threshold never renders as 0.000000."""
    if not status_ok or v in ("", None):
        return DASH
    x = float(v)
    if x <= 0:
        return DASH
    if x < 1e-4:
        m, e = f"{x:.2e}".split("e")
        return rf"${m}\times 10^{{{int(e)}}}$"
    return f"{x:.6f}"


def panel(colspec, header, rows, title=None):
    out = ([rf"\textbf{{{title}}}\\[2pt]"] if title else [])
    out += [rf"\begin{{tabular}}{{{colspec}}}", r"\toprule"]
    out += header + [r"\midrule"]
    out += [" & ".join(r) + r" \\" for r in rows]
    out += [r"\bottomrule", r"\end{tabular}"]
    return out


def table(panels, caption, label):
    out = [r"\begin{table}[htbp]", r"\centering",
           rf"\caption{{{caption}}}", rf"\label{{{label}}}", r"\small"]
    for i, p in enumerate(panels):
        if i:
            out.append(r"\\[10pt]")
        out += p
    out += [r"\end{table}", ""]
    return out


def tabular(colspec, header, rows, caption, label):
    return table([panel(colspec, header, rows)], caption, label)


def main():
    L = [
        r"% Supplementary Tables S1-S4 -- generated by src/revision/make_supplementary_tex.py",
        r"% Do not edit by hand; regenerate with: python -m src.revision.make_supplementary_tex",
        r"\documentclass[11pt]{article}",
        r"\usepackage[margin=2cm,landscape]{geometry}",
        r"\usepackage{booktabs}",
        r"\usepackage{amsmath,amssymb}",   # \mathbb{E} in the S5 caption
        r"\usepackage[T1]{fontenc}",
        r"\renewcommand{\thetable}{S\arabic{table}}",
        r"\begin{document}", "",
    ]

    # ---------------- S1: final-epoch vs fold-8-selected --------------------
    fin = {r["class"]: r for r in rd("supp_a_final_epoch_seed0.csv")}
    f8  = {r["class"]: r for r in rd("e2_per_class_seed0.csv")}
    cfg = lambda rule: json.load(open(CKPT_ROOT / f"acuity35_seed0_{rule}" / "run_config.json"))
    c_fin, c_f8 = cfg("final"), cfg("fold8")
    n_fin = sum(1 for r in fin.values() if r["status"] == "certified")
    n_f8  = sum(1 for r in f8.values()  if r["status"] == "certified")

    p_a = panel("lrr",
        [r"Quantity & Final epoch & Fold-8 selected \\"],
        [[r"Training folds", "1--8", "1--7"],
         [r"Macro AUROC, fold 9",  num(c_fin["fold9_macro_auroc"]),  num(c_f8["fold9_macro_auroc"])],
         [r"Macro AUROC, fold 10", num(c_fin["fold10_macro_auroc"]), num(c_f8["fold10_macro_auroc"])],
         [r"Classes certified (of 33)", str(n_fin), str(n_f8)]],
        "(a) Model-level summary")

    union = sorted({c for c in f8 if f8[c]["status"] == "certified"}
                   | {c for c in fin if fin[c]["status"] == "certified"},
                   key=lambda c: (ORD[f8[c]["tier"]], c))
    rows = []
    for c in union:
        cells = [esc(c), f8[c]["tier"]]
        for src in (fin, f8):
            r = src[c]
            ok = r["status"] == "certified"
            cells += [lam(r["lambda_c"], ok),
                      num(r["test_fnr"]) if ok else DASH,
                      num(r["flag_rate"], 3) if ok else DASH]
        rows.append(cells)
    p_b = panel(
        "llrrrrrr",
        [r"& & \multicolumn{3}{c}{Final epoch} & \multicolumn{3}{c}{Fold-8 selected} \\",
         r"\cmidrule(lr){3-5}\cmidrule(lr){6-8}",
         r"Class & Tier & $\lambda$ & Test FNR & Flag & $\lambda$ & Test FNR & Flag \\"],
        rows, "(b) Per-class operating points")
    L += table([p_a, p_b],
        "Checkpoint rule, final epoch versus fold-8 selected. Taking the final epoch "
        "costs discrimination but not certifications, and several of its certificates "
        "sit at thresholds so low that they flag almost every record, so the counts "
        "alone understate the difference.",
        "tab:s1")

    # ---------------- S2: uniform grid vs exact search ----------------------
    g = sorted(rd("supp_b_grid_comparison.csv"), key=lambda r: (ORD[r["tier"]], r["class"]))
    CHANGED = {"IMI", "ISC_", "NST_", "SBRAD"}
    rows = []
    for r in g:
        mark = r"$^{\dagger}$" if r["class"] in CHANGED else ""
        cells = [esc(r["class"]) + mark, r["tier"]]
        for pre in ("uniform", "exact"):
            ok = r[f"{pre}_status"] == "certified"
            cells += [r[f"{pre}_status"].replace("_", " "), lam(r[f"{pre}_lambda"], ok)]
        rows.append(cells)
    L += tabular(
        "llllll",
        [r"& & \multicolumn{2}{c}{Uniform 1{,}000-point grid} & \multicolumn{2}{c}{Exact search} \\",
         r"\cmidrule(lr){3-4}\cmidrule(lr){5-6}",
         r"Class & Tier & Status & $\lambda$ & Status & $\lambda$ \\"],
        rows,
        "Threshold candidate set: searching the observed calibration positive scores "
        "rather than a uniform grid removes the \\emph{trivial} status entirely, "
        "because that status recorded only the grid's inability to represent a "
        "threshold below its spacing of $0.001$; $^{\\dagger}$ marks the four classes "
        "whose status changes.",
        "tab:s2")

    # ---------------- S3: seed variability ----------------------------------
    sa = rd("e2_seed_auroc.csv")
    p_a = panel(
        "rrrr",
        [r"Seed & Macro AUROC, fold 9 & Macro AUROC, fold 10 & Classes certified \\"],
        [[r["seed"], num(r["macro_auroc_fold9"]), num(r["macro_auroc_fold10"]), r["n_certified"]]
         for r in sa] +
        [[r"\midrule Mean $\pm$ SD",
          f"${np.mean([float(r['macro_auroc_fold9']) for r in sa]):.4f} \\pm "
          f"{np.std([float(r['macro_auroc_fold9']) for r in sa], ddof=1):.4f}$",
          f"${np.mean([float(r['macro_auroc_fold10']) for r in sa]):.4f} \\pm "
          f"{np.std([float(r['macro_auroc_fold10']) for r in sa], ddof=1):.4f}$", ""]],
        "(a) Per-seed model performance")

    sv = sorted(rd("e2_seed_variability.csv"), key=lambda r: (ORD[r["tier"]], r["class"]))
    pm = lambda m, s, nd=4: f"${float(m):.{nd}f} \\pm {float(s):.{nd}f}$"
    p_b = panel(
        "llrrrr",
        [r"Class & Tier & Seeds cert. & $\lambda$ & Test FNR & Flag rate \\"],
        [[esc(r["class"]), r["tier"], f"{r['n_seeds_certified']}/5",
          pm(r["lambda_mean"], r["lambda_sd"], 6),
          pm(r["test_fnr_mean"], r["test_fnr_sd"]),
          pm(r["flag_rate_mean"], r["flag_rate_sd"], 3)] for r in sv],
        "(b) Operating points, mean $\\pm$ SD")
    L += table([p_a, p_b],
        "Training variability across seeds 0--4. Folds 9 and 10 are shared by every "
        "seed, so this spread reflects training randomness rather than the "
        "$(1-\\delta)$ guarantee, and the certified set is identical in all five.",
        "tab:s3")

    # ---------------- S4: uncorrected baselines -----------------------------
    b = sorted(rd("e3_baseline_per_class.csv"), key=lambda r: (ORD[r["tier"]], r["class"]))
    rows = []
    for r in b:
        cells = [esc(r["class"]), r["tier"], num(r["alpha"], 2)]
        for pre in ("ts", "mc"):
            viol = r[f"{pre}_violates"] == "yes"
            fnr = num(r[f"{pre}_test_fnr"])
            cells += [lam(r[f"{pre}_lambda"]),
                      (rf"\textbf{{{fnr}}}" if viol else fnr),
                      f"[{num(r[f'{pre}_fnr_ci95_lo'], 3)}, {num(r[f'{pre}_fnr_ci95_hi'], 3)}]",
                      num(r[f"{pre}_flag_rate"], 3)]
        rows.append(cells)
    L += tabular(
        "llrrrlrrrlr",
        [r"& & & \multicolumn{4}{c}{Temperature scaling} & \multicolumn{4}{c}{MC dropout} \\",
         r"\cmidrule(lr){4-7}\cmidrule(lr){8-11}",
         r"Class & Tier & $\alpha$ & $\lambda$ & Test FNR & 95\% CI & Flag & "
         r"$\lambda$ & Test FNR & 95\% CI & Flag \\"],
        rows,
        "Uncorrected thresholding baselines on the twelve classes the certified "
        "procedure covers: each selects the largest threshold whose fold-9 FNR meets "
        "$\\alpha$, with no allowance for sampling variability between folds; bold "
        "marks a test-fold FNR above target.",
        "tab:s4")

    # ---------------- S5: class-conditional CRC across targets --------------
    cc = rd("e11_crc_configurations.csv")
    p_a = panel(
        "lrrrlrrrlr",
        [r"& & \multicolumn{4}{c}{All calibrated classes} & "
         r"\multicolumn{3}{c}{LTT-certified 12} & \\",
         r"\cmidrule(lr){3-6}\cmidrule(lr){7-9}",
         r"Target & Cal. & Exceed & Rate & 95\% CI & Flag & Exceed & Rate & Flag & Resamp. \\"],
        [[r["config"], r["n_calibrated"],
          f"{r['all_exceedances']}/{r['all_n']}", num(r["all_exceedance_rate"], 3),
          f"[{num(r['all_ci95_lo'],3)}, {num(r['all_ci95_hi'],3)}]",
          num(r["all_mean_flag_rate"], 3),
          f"{r['ltt_exceedances']}/{r['ltt_n']}", num(r["ltt_exceedance_rate"], 3),
          num(r["ltt_mean_flag_rate"], 3),
          num(r["mean_resampling_exceedance_rate"], 3)] for cc_ in [0] for r in cc],
        "(a) Exceedance and selectivity by target")
    crit = [r for r in cc if r["critical_classes_calibrated_at_looser_target"]]
    p_b = panel(
        "ll",
        [r"Uniform target & Critical-tier classes calibrated at a looser target than 0.02 \\"],
        [[r["config"], ", ".join(esc(c) for c in
                                 r["critical_classes_calibrated_at_looser_target"].split())]
         for r in crit],
        "(b) Critical-tier classes receiving a weaker guarantee")
    L += table([p_a, p_b],
        "Class-conditional conformal risk control at the tiered assignment and at three "
        "uniform targets (seed 0, fold 9 calibration, fold 10 test). CRC controls "
        "$\\mathbb{E}[\\mathrm{FNR}] \\le \\alpha$ in expectation, so single-fold "
        "exceedances are expected rather than failures; the final column gives the mean "
        "per-class exceedance rate over 2{,}000 patient-level bootstrap draws, which is the "
        "resampling measure. A looser uniform target calibrates more classes at lower flag "
        "rates, but issues Critical-tier guarantees weaker than those classes require.",
        "tab:s5")

    L += [r"\end{document}", ""]
    TEX.write_text("\n".join(L))
    print(f"wrote {TEX}  ({len(L)} lines, tables S1-S5)")


if __name__ == "__main__":
    main()
